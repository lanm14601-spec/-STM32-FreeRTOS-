static void Glyph(char c, uint8_t *out)
{
    static const uint8_t question[5] = {0x02,0x01,0x51,0x09,0x06};
    static const uint8_t percent[5] = {0x63,0x13,0x08,0x64,0x63};
    if ((c >= 'a') && (c <= 'z')) c = (char)(c - 'a' + 'A');
    if ((c >= '0') && (c <= '9')) memcpy(out, digits[c - '0'], 5U);
    else if ((c >= 'A') && (c <= 'Z')) memcpy(out, letters[c - 'A'], 5U);
    else if (c == '%') memcpy(out, percent, 5U);
    else if (c == ' ') { }
    else if (c == '.') { out[2] = 0x60U; }
    else if (c == ':') { out[2] = 0x36U; }
    else if (c == '-') { memset(out, 0x08, 5U); }
    else if (c == '_') { memset(out, 0x40, 5U); }
    else memcpy(out, question, 5U);
}

void OLED_TextPage(uint8_t pixels[OLED_WIDTH], const char *text)
{
    uint8_t col;
    if (pixels == 0) return;
    memset(pixels, 0, OLED_WIDTH);
    if (text == 0) return;
    for (col = 0U; (col < OLED_TEXT_COLS) && (text[col] != '\0'); ++col)
        Glyph(text[col], &pixels[(uint16_t)col * 6U]);
}
